"""Rebuild src/app/psych-support/s2t.generated.mjs (macOS only; not part of `npm run check`).

    osascript -l JavaScript scripts/s2t-table.jxa.js > /tmp/s2t.raw.txt
    python3 scripts/build-s2t-table.py /tmp/s2t.raw.txt

The raw table is the system ICU Hans-Hant transform, one character at a time.
A character that Big5 can encode is also an ordinary Traditional character
(后, 干, 云, 杰 ...), so it is dropped unless it is on ALWAYS, the hand-checked
list of forms Taiwanese text practically never uses as they are.
"""
import sys
ALWAYS = "万与丰价优体佣儿党厂吨听圣坏夸宁尸岭帘庄异忏怀怜惊愿扑扰挂据机杆杠极构柜栖气泄洁洒洼涂涌痒确离种筑网羡胜腊触赶踊适蚕蜡虫茧荐苹晒复并"
raw = open(sys.argv[1], encoding="utf-8").read().strip()
pairs = [(raw[i], raw[i + 1]) for i in range(0, len(raw), 2)]
keep = []
for simplified, traditional in pairs:
    try:
        simplified.encode("big5"); shared = True
    except UnicodeEncodeError:
        shared = False
    if not shared or simplified in ALWAYS:
        keep.append(simplified + traditional)
out = "src/app/psych-support/s2t.generated.mjs"
open(out, "w", encoding="utf-8").write(
    "// Generated by scripts/build-s2t-table.py from the macOS ICU Hans-Hant transform. Do not edit by hand.\n"
    f"export const S2T_PAIRS = \"{''.join(keep)}\";\n")
print(len(keep), "pairs ->", out)
