import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const read = (path) => JSON.parse(readFileSync(new URL(path, root), "utf8"));
const hash = (value) => createHash("sha256").update(JSON.stringify(value)).digest("hex");
const dimensions = ["content", "privacy", "license", "safety", "localization"];
const actions = ["reflect", "paraphrase", "clarify", "affirm", "suggest", "inform", "repair_misunderstanding", "close"];

/** A build-time attestation gate, not identity verification or clinical approval.
 * This is a separate reviewed-export schema, not the offline raw case-card schema.
 */
export function reviewedExportDigest(card) {
  return hash({ id: card.id, source_id: card.source_id, context: card.reviewed_context,
    response: card.reviewed_response, strategy: card.human_approved_strategy,
    scope: card.reviewed_scope, language: card.language, split: card.split });
}
export function eligibleCase(card, sources) {
  const source = sources.find((s) => s.id === card.source_id);
  if (!source || source.runtime_cases_enabled !== true || source.license_review_status !== "approved"
    || source.privacy_review_status !== "approved" || source.clinical_review_status !== "approved") return false;
  if (card.runtime_retrieval_enabled !== true || card.reviewed_scope !== "general_support"
    || card.approved_use !== "general_support" || card.language !== "zh-TW" || card.split !== "dev"
    || !actions.includes(card.human_approved_strategy) || !card.reviewed_context?.trim() || !card.reviewed_response?.trim()
    || !/^[a-zA-Z0-9_-]{1,100}$/.test(card.id) || card.review_flags?.length) return false;
  const digest = reviewedExportDigest(card);
  return dimensions.every((dimension) => {
    const review = card.reviews?.[dimension];
    return review?.status === "approved" && typeof review.reviewer === "string" && Boolean(review.reviewer.trim())
      && typeof review.note === "string" && Boolean(review.note.trim()) && review.content_sha256 === digest;
  });
}

export function buildKnowledge() {
  const manifest = read("data/psych-support/sources.json");
  const guides = read("data/psych-support/strategy-guides.json");
  const catalog = read("data/psych-support/article-catalog.json");
  const candidateCases = read("data/psych-support/reviewed-cases.json").cases;
  if (!Array.isArray(candidateCases)) throw new Error("Invalid reviewed export");
  if (catalog.length !== 54 || new Set(catalog.map((a) => a.id)).size !== 54) throw new Error("Article catalog coverage changed; review before build");
  for (const guide of guides) {
    if (guide.origin !== "project_authored_nonclinical_guidance" || guide.scope !== "general_support" || !guide.guidance
      || guide.guidance.length > 500) throw new Error("Invalid project guidance");
  }
  const articles = catalog.map((a) => {
    const url = new URL(a.url);
    if (url.origin !== "https://www.fundatalk.com" || !/^\/zh-Hant\/article\/[A-Za-z0-9-]+$/.test(url.pathname)
      || url.search || url.hash || !["metadata_only", "demo_passages"].includes(a.content_mode)
      || a.eligible_for_content_rag !== (a.content_mode === "demo_passages")
      || !a.title || !a.author || !Array.isArray(a.keywords)) throw new Error("Invalid catalog metadata");
    // Deliberately allowlist: never spread imported article fields into runtime.
    return { id: a.id, title: a.title, url: a.url, author: a.author, date_published: a.date_published,
      source_page: a.source_page, keywords: a.keywords };
  });
  const approved = candidateCases.filter((c) => eligibleCase(c, manifest.sources));
  // Fail the build on rejected exports instead of silently publishing a partial corpus.
  if (approved.length !== candidateCases.length) throw new Error("Ineligible reviewed case export; build stopped");
  const cases = approved.map((c) => ({ id: c.id, source_id: c.source_id, context: c.reviewed_context,
    response: c.reviewed_response, strategy: c.human_approved_strategy }));
  const passages = buildPassages(catalog, read("data/psych-support/article-bodies.json"));
  const payload = { version: manifest.version, guides, articles, cases,
    source_status: manifest.sources.map((s) => ({ id: s.id, label: s.label, use: s.use,
      license_review_status: s.license_review_status, clinical_review_status: s.clinical_review_status })),
    content_hash: hash({ guides, articles, cases, passages, sources: manifest.sources }) };
  const output = new URL("src/app/psych-support/knowledge.generated.mjs", root);
  const content = `// Generated by scripts/build-psych-knowledge.mjs. No raw dialogue or summaries; article passages live in passages.generated.mjs.\nexport const KNOWLEDGE = ${JSON.stringify(payload, null, 2)};\n`;
  const passagesOutput = new URL("src/app/psych-support/passages.generated.mjs", root);
  const passagesContent = `// Generated by scripts/build-psych-knowledge.mjs from data/psych-support/article-bodies.json (demo scope).\nexport const PASSAGES = ${JSON.stringify(passages)};\n`;
  return { output, content, passagesOutput, passagesContent,
    counts: { guides: guides.length, article_links: articles.length, approved_cases: cases.length, passages: passages.length } };
}

/** Demo-scope passages: each article body is cut into ~400-character chunks that keep their heading.
 * Only articles flagged demo_passages get passages; a chunk is plain text, never a summary. */
export function buildPassages(catalog, bodies) {
  const MAX = 400, MIN_BEFORE_HEADING_BREAK = 160;
  const passages = [];
  for (const article of catalog) {
    if (article.content_mode !== "demo_passages") continue;
    const body = bodies.articles.find((b) => b.id === article.id);
    if (!body || !Array.isArray(body.sections) || !body.sections.length) throw new Error(`Missing article body: ${article.id}`);
    let chunk = { heading: "", text: "" };
    const flush = () => { if (chunk.text.trim()) passages.push({ id: `${article.id}#${passages.filter((p) => p.a === article.id).length + 1}`, a: article.id, h: chunk.heading, t: chunk.text.trim() }); chunk = { heading: "", text: "" }; };
    for (const section of body.sections) {
      const heading = String(section.heading || "").trim();
      if (chunk.text.length >= MIN_BEFORE_HEADING_BREAK) flush();
      if (!chunk.text) chunk.heading = heading; else if (heading) chunk.text += `\n${heading}：`;
      const sentences = String(section.text).split(/(?<=[。！？!?])|\n/).map((s) => s.trim()).filter(Boolean);
      for (const sentence of sentences) {
        if (chunk.text && chunk.text.length + sentence.length > MAX) { const h = chunk.heading; flush(); chunk.heading = h; }
        chunk.text += (chunk.text && !chunk.text.endsWith("：") ? "\n" : "") + sentence;
      }
    }
    flush();
    // Fold tiny tail chunks into their predecessor so no passage is a lone heading or sentence.
    const own = passages.filter((p) => p.a === article.id);
    for (let i = own.length - 1; i > 0; i--) {
      if (own[i].t.length < 80) { own[i - 1].t += `\n${own[i].h ? `${own[i].h}：` : ""}${own[i].t}`; passages.splice(passages.indexOf(own[i]), 1); own.splice(i, 1); }
    }
    own.forEach((p, i) => { p.id = `${article.id}#${i + 1}`; });
  }
  return passages;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = buildKnowledge();
  if (process.argv.includes("--check")) {
    if (readFileSync(result.output, "utf8") !== result.content) throw new Error("Generated knowledge is stale");
    if (readFileSync(result.passagesOutput, "utf8") !== result.passagesContent) throw new Error("Generated passages are stale");
  } else { writeFileSync(result.output, result.content); writeFileSync(result.passagesOutput, result.passagesContent); }
  process.stdout.write(JSON.stringify(result.counts) + "\n");
}
