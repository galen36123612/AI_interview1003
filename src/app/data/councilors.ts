export const DISTRICT_TO_CONSTITUENCY: Record<string, number> = {
  "士林區": 1,
  "北投區": 1,
  "內湖區": 2,
  "南港區": 2,
  "松山區": 3,
  "信義區": 3,
  "中山區": 4,
  "大同區": 4,
  "中正區": 5,
  "萬華區": 5,
  "大安區": 6,
  "文山區": 6,
  "平地原住民": 7,
  "山地原住民": 8
};

function normalizeDistrict(input: string) {
  const value = input.trim().replace(/\s+/g, "");
  if (!value) return "";
  if (value === "平地原住民" || value === "山地原住民") return value;
  return value.endsWith("區") ? value : `${value}區`;
}

function normalizeName(input: string) {
  return input.trim().replace(/\s+/g, "");
}

export function lookupCouncilorsByDistrict(districtInput: string) {
  const district = normalizeDistrict(districtInput);
  const constituency = DISTRICT_TO_CONSTITUENCY[district];

  if (!constituency) {
    return {
      found: false as const,
      reason: "invalid_district" as const,
      district,
      message: "找不到對應的臺北市議員選區。",
    };
  }

  const members = TAIPEI_COUNCILORS.filter(
    (item) => item.constituency === constituency && item.status === "current"
  );

  return {
    found: members.length > 0 as true | false,
    district,
    constituency,
    constituencyName: members[0]?.constituencyName,
    data: members,
    verifiedAt: "2026-09-02",
  };
}

export function lookupCouncilorByName(nameInput: string) {
  const name = normalizeName(nameInput);
  const matches = TAIPEI_COUNCILORS.filter(
    (item) => normalizeName(item.name) === name && item.status === "current"
  );

  if (!matches.length) {
    return {
      found: false as const,
      reason: "not_found" as const,
      name,
      message: "本地市議員資料沒有找到這個名字，請改查最新官方資料。",
    };
  }

  return {
    found: true as const,
    data: matches,
    verifiedAt: "2026-09-02",
  };
}

